# ============================================================
# التحقق من الصفحة
# ============================================================

def validate_page(page, expected_title):

    # --------------------------------------------------------
    # التحقق من العنوان
    # --------------------------------------------------------

    if page.title() != expected_title:

        print(
            "  فشل التحقق من عنوان الصفحة."
        )

        return False

    # --------------------------------------------------------
    # التحقق من نطاق المقالات
    # --------------------------------------------------------

    if page.namespace() != 0:

        print(
            f"  الصفحة ليست في نطاق المقالات. "
            f"namespace={page.namespace()}"
        )

        return False

    # --------------------------------------------------------
    # التحقق من وجود الصفحة
    # --------------------------------------------------------

    if not page.exists():

        print(
            "  الصفحة غير موجودة."
        )

        return False

    # --------------------------------------------------------
    # تجاهل التحويلات
    # --------------------------------------------------------

    if page.isRedirectPage():

        print(
            "  الصفحة تحويلة."
        )

        return False

    return True


# ============================================================
# التحقق من botMayEdit
# ============================================================

def check_bot_may_edit(page):
    """
    يتحقق من botMayEdit() إذا كانت متاحة
    في إصدار Pywikibot المستخدم.

    إذا لم تكن متاحة، يتوقف البوت
    بدل تجاوز الحماية.
    """

    method = getattr(
        page,
        "botMayEdit",
        None,
    )

    if method is None:

        print(
            "  إصدار Pywikibot الحالي لا يوفر "
            "page.botMayEdit()."
        )

        print(
            "🛑 تم إيقاف البوت ولن يتم الحفظ."
        )

        return False

    if not callable(method):

        print(
            "  botMayEdit ليست دالة قابلة للاستدعاء."
        )

        return False

    try:

        result = method()

    except Exception as error:

        print(
            f"  فشل botMayEdit(): {error}"
        )

        return False

    if result is False:

        print(
            "  botMayEdit() رفض تعديل الصفحة."
        )

        return False

    print(
        "✓ botMayEdit() يسمح بالتعديل."
    )

    return True


# ============================================================
# بناء التعديل الآمن
# ============================================================

def build_safe_edit(text):

    text = normalize_text(text)

    # --------------------------------------------------------
    # عدد جميع صيغ references
    # --------------------------------------------------------

    all_references = count_matches(
        ANY_REFERENCES_PATTERN,
        text,
    )

    # --------------------------------------------------------
    # عدد references البسيط
    # --------------------------------------------------------

    simple_references = count_matches(
        OLD_PATTERN,
        text,
    )

    print(
        f" جميع وسوم references: "
        f"{all_references}"
    )

    print(
        f" وسوم <references /> البسيطة: "
        f"{simple_references}"
    )

    # --------------------------------------------------------
    # لا يوجد references بسيط
    # --------------------------------------------------------

    if simple_references == 0:

        print(
            "✓ لا يوجد <references /> بسيط."
        )

        return None

    # --------------------------------------------------------
    # أكثر من references بسيط
    # --------------------------------------------------------

    if simple_references > 1:

        print(
            "  يوجد أكثر من <references />."
        )

        print(
            "🛑 لن يتم تعديل الصفحة."
        )

        return None

    # --------------------------------------------------------
    # وجود صيغة أخرى
    # --------------------------------------------------------

    if all_references != 1:

        print(
            "  توجد صيغة أخرى من references "
            "أو أكثر من وسم واحد."
        )

        print(
            "🛑 لن يتم تعديل الصفحة."
        )

        return None

    # --------------------------------------------------------
    # البحث عن {{مراجع}}
    # --------------------------------------------------------

    maraj_count = count_matches(
        MARAJ_PATTERN,
        text,
    )

    print(
        f" عدد {{مراجع}} الموجود: "
        f"{maraj_count}"
    )

    if maraj_count > 0:

        print(
            "  يوجد {{مراجع}} بالفعل."
        )

        print(
            "🛑 لن يتم استبدال أي شيء."
        )

        return None

    # --------------------------------------------------------
    # الاستبدال
    # --------------------------------------------------------

    new_text = OLD_PATTERN.sub(
        NEW_TEXT,
        text,
        count=1,
    )

    # --------------------------------------------------------
    # التأكد من حدوث تغيير
    # --------------------------------------------------------

    if new_text == text:

        print(
            "  لم ينتج أي تغيير."
        )

        return None

    # --------------------------------------------------------
    # يجب ألا يبقى references البسيط
    # --------------------------------------------------------

    if count_matches(
        OLD_PATTERN,
        new_text,
    ) != 0:

        print(
            "  ما زال <references /> موجودًا."
        )

        return None

    # --------------------------------------------------------
    # يجب وجود {{مراجع}} واحد
    # --------------------------------------------------------

    if count_matches(
        MARAJ_PATTERN,
        new_text,
    ) != 1:

        print(
            "  عدد {{مراجع}} بعد التعديل غير متوقع."
        )

        return None

    # --------------------------------------------------------
    # تحقق صارم من التغيير
    # --------------------------------------------------------

    expected = OLD_PATTERN.sub(
        NEW_TEXT,
        text,
        count=1,
    )

    if new_text != expected:

        print(
            "  التعديل لا يطابق التعديل المتوقع."
        )

        return None

    return new_text


# ============================================================
# معالجة الصفحة
# ============================================================

def process_page(site, title):

    page = pywikibot.Page(
        site,
        title,
    )

    print("\n" + "=" * 70)
    print(f"🤖 الصفحة: {title}")
    print("=" * 70)

    # --------------------------------------------------------
    # التحقق من الصفحة
    # --------------------------------------------------------

    if not validate_page(
        page,
        title,
    ):
        return

    # --------------------------------------------------------
    # القراءة الأولى
    # --------------------------------------------------------

    print(
        "📖 قراءة الصفحة..."
    )

    original_text = normalize_text(
        page.text
    )

    if not original_text:

        print(
            "  الصفحة فارغة."
        )

        return

    # --------------------------------------------------------
    # botMayEdit
    # --------------------------------------------------------

    if not check_bot_may_edit(page):
        return

    # --------------------------------------------------------
    # بناء التعديل
    # --------------------------------------------------------

    new_text = build_safe_edit(
        original_text
    )

    if new_text is None:
        return

    # --------------------------------------------------------
    # عرض Diff
    # --------------------------------------------------------

    print("\n" + "=" * 70)
    print("🔍 DIFF")
    print("=" * 70)

    pywikibot.showDiff(
        original_text,
        new_text,
    )

    # --------------------------------------------------------
    # التأكيد الأول
    # --------------------------------------------------------

    answer = input(
        "\nهل تريد متابعة التعديل؟ [y/N]: "
    ).strip()

    if answer.lower() != "y":

        print(
            "✗ تم إلغاء التعديل."
        )

        return

    # --------------------------------------------------------
    # إعادة القراءة
    # --------------------------------------------------------

    print(
        "\n🔄 إعادة قراءة الصفحة..."
    )

    current_text = normalize_text(
        page.text
    )

    if current_text != original_text:

        print(
            "  الصفحة تغيرت منذ القراءة الأولى."
        )

        print(
            "🛑 لن يتم الحفظ."
        )

        return

    print(
        "✓ الصفحة لم تتغير."
    )

    # --------------------------------------------------------
    # botMayEdit مرة ثانية
    # --------------------------------------------------------

    if not check_bot_may_edit(page):
        return

    # --------------------------------------------------------
    # إعادة بناء التعديل
    # --------------------------------------------------------

    final_text = build_safe_edit(
        current_text
    )

    if final_text is None:

        print(
            "  لم يعد التعديل صالحًا."
        )

        return

    # --------------------------------------------------------
    # مقارنة التعديل
    # --------------------------------------------------------

    if final_text != new_text:

        print(
            "  نتيجة التعديل تغيرت."
        )

        print(
            "🛑 تم إيقاف الحفظ."
        )

        return

    print(
        "✓ التعديل مطابق للمعاينة السابقة."
    )

    # --------------------------------------------------------
    # Diff النهائي
    # --------------------------------------------------------

    print("\n" + "=" * 70)
    print("🔍 DIFF النهائي")
    print("=" * 70)

    pywikibot.showDiff(
        current_text,
        final_text,
    )

    # --------------------------------------------------------
    # التأكيد النهائي
    # --------------------------------------------------------

    final_answer = input(
        "\n الحفظ النهائي.\n"
        "اكتب YES حرفيًا للحفظ: "
    )

    if final_answer != "YES":

        print(
            "✗ لم تتم كتابة YES."
        )

        print(
            "🛑 تم إلغاء الحفظ."
        )

        return

    # --------------------------------------------------------
    # آخر قراءة
    # --------------------------------------------------------

    print(
        "\n🔐 الفحص الأخير..."
    )

    latest_text = normalize_text(
        page.text
    )

    if latest_text != current_text:

        print(
            "  الصفحة تغيرت قبل الحفظ."
        )

        print(
            "🛑 تم إلغاء الحفظ."
        )

        return

    # --------------------------------------------------------
    # آخر botMayEdit
    # --------------------------------------------------------

    if not check_bot_may_edit(page):
        return

    # --------------------------------------------------------
    # آخر تحقق للمحتوى
    # --------------------------------------------------------

    if count_matches(
        OLD_PATTERN,
        latest_text,
    ) != 1:

        print(
            "  لم يعد هناك <references /> واحد مطابق."
        )

        return

    if count_matches(
        ANY_REFERENCES_PATTERN,
        latest_text,
    ) != 1:

        print(
            "  تغير عدد وسوم references."
        )

        return

    if count_matches(
        MARAJ_PATTERN,
        latest_text,
    ) != 0:

        print(
            "  ظهر {{مراجع}} قبل الحفظ."
        )

        return

    # --------------------------------------------------------
    # الحفظ
    # --------------------------------------------------------

    page.text = final_text

    page.save(
        summary=EDIT_SUMMARY,
        minor=True,
        bot=True,
        force=False,
    )

    print(
        "\n✅ تم الحفظ بنجاح."
    )


