# -*- coding: utf-8 -*-

import re
import pywikibot


# ============================================================
# الإعدادات
# ============================================================

OLD_PATTERN = re.compile(
    r"<references\s*/\s*>",
    re.IGNORECASE,
)

ANY_REFERENCES_PATTERN = re.compile(
    r"<references\b[^>]*>",
    re.IGNORECASE,
)

MARAJ_PATTERN = re.compile(
    r"\{\{\s*مراجع\s*\}\}",
    re.IGNORECASE,
)

NEW_TEXT = "{{مراجع}}"

EDIT_SUMMARY = (
    "استبدال وسم <references /> بقالب {{مراجع}}"
)

# صفحة واحدة فقط في كل تشغيل
MAX_PAGES_PER_RUN = 1


