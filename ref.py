def normalize_text(text):
    """
    توحيد نهايات الأسطر للمقارنة فقط.
    """
    return text.replace("\r\n", "\n").replace("\r", "\n")


def count_matches(pattern, text):
    return len(pattern.findall(text))


# ============================================================
# التحقق من الموقع
# ============================================================

def validate_site(site):

    if site.family.name != "wikipedia":
        print("  الموقع ليس Wikipedia.")
        return False

    if site.lang != "ar":
        print("  الموقع ليس ويكيبيديا العربية.")
        return False

    if site.code != "ar":
        print("  رمز الموقع ليس ar.")
        return False

    return True


