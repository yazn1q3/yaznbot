# اختيار مقالة عشوائية مناسبة
# ============================================================

def get_random_page(site, max_attempts=100):
    """
    البحث عن مقالة عشوائية تحتوي على
    <references /> بسيط واحد فقط.

    لا يتم تعديل أي صفحة أثناء البحث.
    """

    for attempt in range(1, max_attempts + 1):

        print(
            f"\n  محاولة اختيار عشوائي "
            f"({attempt}/{max_attempts})..."
        )

        request = site.simple_request(
            action="query",
            generator="random",
            grnnamespace=0,
            grnlimit=1,
        )

        data = request.submit()

        pages = (
            data
            .get("query", {})
            .get("pages", {})
        )

        for page_data in pages.values():

            title = page_data.get("title")

            if not title:
                continue

            page = pywikibot.Page(
                site,
                title,
            )

            # ------------------------------------------------
            # تحقق من النطاق
            # ------------------------------------------------

            if page.namespace() != 0:
                print(
                    f"⏭️ تجاهل: {title} "
                    f"(ليس نطاق المقالات)"
                )
                continue

            # ------------------------------------------------
            # تجاهل التحويلات
            # ------------------------------------------------

            if page.isRedirectPage():
                print(
                    f"⏭️ تجاهل: {title} "
                    f"(تحويلة)"
                )
                continue

            # ------------------------------------------------
            # قراءة الصفحة
            # ------------------------------------------------

            try:
                text = normalize_text(
                    page.text
                )
            except Exception as error:
                print(
                    f" تعذر قراءة {title}: "
                    f"{error}"
                )
                continue

            # ------------------------------------------------
            # التحقق من references
            # ------------------------------------------------

            simple_count = count_matches(
                OLD_PATTERN,
                text,
            )

            all_count = count_matches(
                ANY_REFERENCES_PATTERN,
                text,
            )

            maraj_count = count_matches(
                MARAJ_PATTERN,
                text,
            )

            print(
                f"📄 {title}"
            )

            print(
                f"   references البسيط: "
                f"{simple_count}"
            )

            print(
                f"   جميع references: "
                f"{all_count}"
            )

            print(
                f"   {{مراجع}}: "
                f"{maraj_count}"
            )

            # ------------------------------------------------
            # الصفحة المناسبة
            # ------------------------------------------------

            if simple_count == 1 and all_count == 1:

                if maraj_count == 0:

                    print(
                        "\n✅ تم العثور على مقالة مناسبة:"
                    )

                    print(
                        f"🎯 {title}"
                    )

                    return title

            print(
                "⏭️ المقالة غير مناسبة، "
                "سيتم اختيار مقالة أخرى."
            )

    print(
        "\n  لم يتم العثور على مقالة مناسبة "
        f"بعد {max_attempts} محاولة."
    )

    return None


